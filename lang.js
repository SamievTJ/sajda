// Global state for language
let currentLang = localStorage.getItem('sajda_lang') || localStorage.getItem('nur_lang') || 'tj';

// ── Helper: get translation ────────────────────────────────────────────────
function t(key) {
  const d = translations[currentLang];
  return (d && d[key] !== undefined) ? d[key] : (translations.tj[key] || key);
}

// ── Translate all [data-i18n] elements ────────────────────────────────────
function translatePage() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else {
      el.innerText = val;
    }
  });

  // Translate placeholders
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-ph'));
  });

  document.documentElement.lang = currentLang;
}

// ── Switch language ────────────────────────────────────────────────────────
function toggleLanguage() {
  currentLang = currentLang === 'tj' ? 'ru' : 'tj';
  localStorage.setItem('sajda_lang', currentLang);
  localStorage.setItem('nur_lang', currentLang);

  const langBtn = document.getElementById('langToggleBtn');
  if (langBtn) {
    langBtn.innerHTML = currentLang === 'tj' ? '🇷🇺 Рус' : '🇹🇯 Тоҷ';
  }

  translatePage();
  window.dispatchEvent(new Event('languageChanged'));
}

// ── Initialize on load ────────────────────────────────────────────────────
window.addEventListener('DOMContentLoaded', () => {
  translatePage();
  const langBtn = document.getElementById('langToggleBtn');
  if (langBtn) {
    langBtn.innerHTML = currentLang === 'tj' ? '🇷🇺 Рус' : '🇹🇯 Тоҷ';
  }
});
