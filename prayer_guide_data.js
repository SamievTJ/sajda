function getPrayersGuideData() {
  const isRu = currentLang === 'ru';
  const localizedData = {};
  
  for (const [key, data] of Object.entries(prayersGuideData)) {
    localizedData[key] = {
      name: isRu ? data.name_ru : data.name,
      rakats: isRu ? data.rakats_ru : data.rakats,
      steps: data.steps.map(s => ({
        num: isRu ? s.num_ru : s.num,
        name: isRu ? s.name_ru : s.name,
        desc: isRu ? s.desc_ru : s.desc,
        visual: s.visual,
        arabic: s.arabic,
        translit: s.translit,
        translation: s.translation
      }))
    };
  }
  
  return localizedData;
}
